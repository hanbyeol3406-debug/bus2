def estimate_segment_min(u: str, v: str) -> int:
    if u == v:
        return 0
    nu, nv = NODES.get(u), NODES.get(v)
    if not nu or not nv:
        return 4
    dist = math.hypot(nu["x"] - nv["x"], nu["y"] - nv["y"])
    return int(max(2, min(7, round(dist * 0.38))))


